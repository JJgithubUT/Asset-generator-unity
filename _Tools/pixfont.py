ROWS = 12          # fila 0-1: acento de mayuscula; 2-9: mayuscula (8 px); 10-11: descendentes
ADV = 6
ACCENT = {
    'á': ('a', 'acute'), 'é': ('e', 'acute'), 'í': ('i', 'acute'), 'ó': ('o', 'acute'), 'ú': ('u', 'acute'),
    'Á': ('A', 'acute'), 'É': ('E', 'acute'), 'Í': ('I', 'acute'), 'Ó': ('O', 'acute'), 'Ú': ('U', 'acute'),
    'ü': ('u', 'diaer'), 'Ü': ('U', 'diaer'), 'ñ': ('n', 'tilde'), 'Ñ': ('N', 'tilde'),
}
MARK = {'acute': ['...#.', '..#..'], 'diaer': ['.#.#.', '.....'], 'tilde': ['.##.#', '#.##.']}


def base_grid(ch):
    rows = G[ch]
    grid = [[0] * 5 for _ in range(ROWS)]

    def put(r, s):
        for i, c in enumerate(s):
            if c == '#': grid[r][i] = 1
    if ch in 'ij':
        put(3, rows[0])
        for k, r in enumerate(rows[2:]): put(5 + k, r)
    elif ch == 't':
        for k, r in enumerate(rows[:7]): put(3 + k, r)
    elif rows[0] != '.....':                      # mayuscula, digito, ascendente, puntuacion alta
        seq = rows[:4] + [rows[3]] + rows[4:7]    # se duplica la fila central: 8 filas de alto
        for k, r in enumerate(seq): put(2 + k, r)
        for k, r in enumerate(rows[7:]): put(10 + k, r)
    else:                                         # cuerpo de minuscula (altura de x = 5)
        for k, r in enumerate(rows[2:7]): put(5 + k, r)
        for k, r in enumerate(rows[7:]): put(10 + k, r)
    if ch in '.,:;-_+=*' or ch in "'\"":          # signos propios: se dejan con su posicion clasica
        grid = [[0] * 5 for _ in range(ROWS)]
        for k, r in enumerate(rows): put(3 + k, r)
    return grid


def glyph_grid(ch):
    if ch in ACCENT:
        b, m = ACCENT[ch]
        grid = base_grid(b)
        top = 0 if b.isupper() else 2
        for k, r in enumerate(MARK[m]):
            for i, c in enumerate(r):
                if c == '#': grid[top + k][i] = 1
        if m == 'diaer' and b.isupper():
            grid[1] = [0] * 5
        return grid
    if ch not in G: ch = '?'
    return base_grid(ch)


ALL_CHARS = [chr(c) for c in range(33, 127) if chr(c) in G] + list(ACCENT) + ['¿', '¡']


def draw_text(cv, x, y, text, col, scale=1, spacing=0):
    """Escribe texto en un lienzo. (x,y) = esquina superior de la fila 2 (tope de mayuscula)."""
    cx = x
    for ch in text:
        if ch == ' ':
            cx += (4 + spacing) * scale
            continue
        gr = glyph_grid(ch)
        for r in range(ROWS):
            for c in range(5):
                if gr[r][c]:
                    for sy in range(scale):
                        for sx in range(scale):
                            cv.set(cx + c * scale + sx, y + (r - 2) * scale + sy, col)
        cx += (ADV + spacing) * scale
    return cx


def text_width(text, scale=1, spacing=0):
    return sum(((4 if ch == ' ' else ADV) + spacing) * scale for ch in text)


def build_ttf(path):
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    U = 100
    chars = [' '] + ALL_CHARS
    names = ['.notdef'] + ['space' if c == ' ' else 'uni%04X' % ord(c) for c in chars]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({ord(c): n for c, n in zip(chars, names[1:])})
    glyphs, metrics = {}, {}
    # .notdef: caja
    pen = TTGlyphPen(None)
    pen.moveTo((0, 0)); pen.lineTo((0, 800)); pen.lineTo((500, 800)); pen.lineTo((500, 0)); pen.closePath()
    pen.moveTo((100, 100)); pen.lineTo((400, 100)); pen.lineTo((400, 700)); pen.lineTo((100, 700)); pen.closePath()
    glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (600, 0)
    for ch, n in zip(chars, names[1:]):
        pen = TTGlyphPen(None)
        if ch != ' ':
            gr = glyph_grid(ch)
            for r in range(ROWS):
                c = 0
                while c < 5:
                    if gr[r][c]:
                        c0 = c
                        while c < 5 and gr[r][c]: c += 1
                        y1 = (10 - r) * U
                        y0 = y1 - U
                        x0, x1 = c0 * U, c * U
                        pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
                    else:
                        c += 1
        glyphs[n] = pen.glyph()
        metrics[n] = (400 if ch == ' ' else ADV * U, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=1000, descent=-200)
    fb.setupNameTable({'familyName': 'Mercadieval Pixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=1000, sTypoDescender=-200, usWinAscent=1000, usWinDescent=200, sxHeight=500, sCapHeight=800)
    fb.setupPost()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fb.save(path)


